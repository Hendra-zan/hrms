// Helper: ambil daftar nama provinsi untuk dropdown Provinsi
export const getProvinsiList = (): string[] =>
  WILAYAH_INDONESIA.map((p) => p.nama);

// Helper: ambil daftar kota berdasarkan nama provinsi
export const getKotaByProvinsi = (namaProvinsi: string): KotaData[] => {
  const provinsi = WILAYAH_INDONESIA.find(
    (p) => p.nama.toLowerCase() === namaProvinsi.toLowerCase()
  );
  return provinsi ? provinsi.kota : [];
};

// Helper: ambil kode pos berdasarkan nama provinsi + nama kota
export const getKodePosByKota = (namaProvinsi: string, namaKota: string): string => {
  const kota = getKotaByProvinsi(namaProvinsi).find(
    (k) => k.nama.toLowerCase() === namaKota.toLowerCase()
  );
  return kota ? kota.kodePos : '';
};
